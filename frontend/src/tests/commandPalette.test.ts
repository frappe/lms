/**
 * The command palette, one file so CommandPalette and the real Dialog +
 * Listbox load once. The suites that stub frappe-ui differently stay apart:
 * commandPaletteEmptyState (a reactive resource) and
 * commandPaletteRequestLifetime (a held debounce tick).
 *
 * Shortcut hints: `lucide-*` are mask classes that the icon plugin paints with
 * `background-color: currentColor`. Putting `bg-surface-gray-2` on the icon to
 * give it a chip therefore repaints the glyph itself light grey and draws no
 * chip at all, which is how the arrows went nearly invisible. The chip has to
 * be a wrapper, and that is only visible in the classes.
 *
 * Icons are `lucide-*` classes generated by the frappe-ui vite plugin from
 * lucide-static. The names still have to be real: a class that generates
 * nothing renders an empty box, silently. The guard arrived because the
 * imported-component form failed harder and later: `House` is lucide's
 * post-0.400 name for `Home` and this bench is on 0.383, so the browser's
 * strict ESM refused the module and the palette died on load while every suite
 * stayed green, vitest's interop having handed back `undefined` for the
 * missing export.
 *
 * Categories: category drill-down, and the rows that are gated on a role. The
 * client-side gate here only keeps a row off screen. What a search actually
 * returns is decided by `get_grouped_results` on the server, which is where the
 * permission check that matters lives.
 *
 * Search: every case is a bug the palette shipped with: every non-course hit
 * routed into the batch page, and one typed character blanked the dialog
 * because the results pane took over before the search was allowed to run.
 * Arrow-key highlighting and Enter-to-select are `frappe-ui/experimental`'s own
 * `CommandPalette` behaviour now — the library's own test suite covers that;
 * these tests drive selection with a click, which reaches the same LMS-owned
 * `onSelect` handler.
 */
