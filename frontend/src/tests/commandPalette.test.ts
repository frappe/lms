const resource = {
	next: null as unknown,
	params: null as any,
	submit: vi.fn(async (params: any) => {
		resource.params = params
		return resource.next
	}),
}

vi.mock('frappe-ui', () => ({
	createResource: () => resource,
	debounce: (fn: (...args: unknown[]) => void) =>
		Object.assign(fn, { cancel: () => {} }),
}))

// Settings is addressed by the URL hash, so opening it is a navigation and the
// stub carries what pushSettingsHash reads (hash, query). openFormRoute reads
// fullPath and matched: it stamps the location it is leaving into
// history.state so App.vue can keep that page rendered under the form's dialog.
const router = {
	currentRoute: {
		value: { hash: '', query: {}, fullPath: '/courses', matched: [{}] },
	},
	options: { history: { state: {} } },
	push: vi.fn(),
	replace: vi.fn(),
}
const push = router.push
vi.mock('vue-router', () => ({ useRouter: () => router }))

